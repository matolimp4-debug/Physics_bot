@dp.callback_query(F.data.startswith("ans:"))
async def handle_answer_callback(query: types.CallbackQuery):
   parts = query.data.split(":")
   statement_id = int(parts[1])
   user_choice = int(parts[2])
   user_id = query.from_user.id

   st = get_statement_by_id(statement_id)
   if not st:
       await query.answer("Утверждение не найдено.", show_alert=True)
       return

   is_correct_ans = (user_choice == st["is_correct"])
   user = get_user(user_id)
   current_mode = user["mode"]

   if is_correct_ans:
       status_header = "🟢 **ВЕРНО! Отличный ответ!**"
       if current_mode == "review":
           remove_mistake(user_id, statement_id)
       else:
           increment_correct(user_id)
   else:
       status_header = "🔴 **НЕВЕРНО! Допущена ошибка.**"
       add_mistake(user_id, statement_id)

   correct_word = "ВЕРНО ✅" if st["is_correct"] == 1 else "НЕВЕРНО ❌"

   result_text = (
       f"{status_header}\n\n"
       f"📝 **Утверждение:** «_{st['text']}_»\n"
       f"Правильный статус: **{correct_word}**\n\n"
       f"💡 **Объяснение:**\n{st['explanation']}"
   )

   await query.message.edit_text(
       result_text,
       reply_markup=get_post_answer_keyboard(statement_id),
       parse_mode="Markdown"
   )
   await query.answer()


