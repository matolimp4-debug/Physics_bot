def init_db():
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()

   cur.execute("""
       CREATE TABLE IF NOT EXISTS statements (
           id INTEGER PRIMARY KEY AUTOINCREMENT,
           topic TEXT NOT NULL,
           text TEXT NOT NULL UNIQUE,
           is_correct INTEGER NOT NULL,
           explanation TEXT NOT NULL
       )
   """)

   cur.execute("""
       CREATE TABLE IF NOT EXISTS users (
           user_id INTEGER PRIMARY KEY,
           mode TEXT DEFAULT 'study',
           current_statement_id INTEGER DEFAULT NULL,
           correct_count INTEGER DEFAULT 0,
           wrong_count INTEGER DEFAULT 0
       )
   """)

   cur.execute("""
       CREATE TABLE IF NOT EXISTS mistakes (
           user_id INTEGER,
           statement_id INTEGER,
           PRIMARY KEY (user_id, statement_id),
           FOREIGN KEY (statement_id) REFERENCES statements(id)
       )
   """)

   # Проверяем наполненность базы (не менее 700 записей)
   cur.execute("SELECT COUNT(*) FROM statements")
   count = cur.fetchone()[0]
   if count < 700:
       logger.info(f"Заполняем базу утверждений. Текущее количество: {count}")
       statements = build_full_statements_pool()
       cur.executemany(
           "INSERT OR IGNORE INTO statements (topic, text, is_correct, explanation) VALUES (?, ?, ?, ?)",
           statements,
       )
       conn.commit()
       cur.execute("SELECT COUNT(*) FROM statements")
       new_count = cur.fetchone()[0]
       logger.info(f"База успешно синхронизирована: {new_count} утверждений загружено.")

   conn.commit()
   conn.close()


def get_user(user_id: int) -> Dict[str, Any]:
   conn = sqlite3.connect(DB_PATH)
   conn.row_factory = sqlite3.Row
   cur = conn.cursor()
   cur.execute("SELECT * FROM users WHERE user_id = ?", (user_id,))
   row = cur.fetchone()
   if not row:
       cur.execute(
           "INSERT INTO users (user_id, mode, correct_count, wrong_count) VALUES (?, 'study', 0, 0)",
           (user_id,),
       )
       conn.commit()
       cur.execute("SELECT * FROM users WHERE user_id = ?", (user_id,))
       row = cur.fetchone()
   user_dict = dict(row)
   conn.close()
   return user_dict


def set_user_mode(user_id: int, mode: str):
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("UPDATE users SET mode = ? WHERE user_id = ?", (mode, user_id))
   conn.commit()
   conn.close()


def set_user_current_statement(user_id: int, statement_id: Optional[int]):
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("UPDATE users SET current_statement_id = ? WHERE user_id = ?", (statement_id, user_id))
   conn.commit()
   conn.close()


def get_statement_by_id(st_id: int) -> Optional[Dict[str, Any]]:
   conn = sqlite3.connect(DB_PATH)
   conn.row_factory = sqlite3.Row
   cur = conn.cursor()
   cur.execute("SELECT * FROM statements WHERE id = ?", (st_id,))
   row = cur.fetchone()
   conn.close()
   return dict(row) if row else None


def get_next_statement(user_id: int, mode: str) -> Optional[Dict[str, Any]]:
   conn = sqlite3.connect(DB_PATH)
   conn.row_factory = sqlite3.Row
   cur = conn.cursor()

   if mode == "review":
       cur.execute("""
           SELECT s.* FROM statements s
           JOIN mistakes m ON s.id = m.statement_id
           WHERE m.user_id = ?
           ORDER BY RANDOM() LIMIT 1
       """, (user_id,))
   else:
       cur.execute("SELECT * FROM statements ORDER BY RANDOM() LIMIT 1")

   row = cur.fetchone()
   conn.close()
   return dict(row) if row else None


def count_user_mistakes(user_id: int) -> int:
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("SELECT COUNT(*) FROM mistakes WHERE user_id = ?", (user_id,))
   count = cur.fetchone()[0]
   conn.close()
   return count


def add_mistake(user_id: int, statement_id: int):
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("INSERT OR IGNORE INTO mistakes (user_id, statement_id) VALUES (?, ?)", (user_id, statement_id))
   cur.execute("UPDATE users SET wrong_count = wrong_count + 1 WHERE user_id = ?", (user_id,))
   conn.commit()
   conn.close()


def remove_mistake(user_id: int, statement_id: int):
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("DELETE FROM mistakes WHERE user_id = ? AND statement_id = ?", (user_id, statement_id))
   cur.execute("UPDATE users SET correct_count = correct_count + 1 WHERE user_id = ?", (user_id,))
   conn.commit()
   conn.close()


def increment_correct(user_id: int):
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("UPDATE users SET correct_count = correct_count + 1 WHERE user_id = ?", (user_id,))
   conn.commit()
   conn.close()


def get_total_statements_count() -> int:
   conn = sqlite3.connect(DB_PATH)
   cur = conn.cursor()
   cur.execute("SELECT COUNT(*) FROM statements")
   cnt = cur.fetchone()[0]
   conn.close()
   return cnt


